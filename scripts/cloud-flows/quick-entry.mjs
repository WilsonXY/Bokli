import assert from "node:assert/strict";
export default async function quickEntry({ page, shot: rawShot }) {
  const shot = async name => { await page.waitForTimeout(700); await rawShot(name,page,{fullPage:false}); };
  await page.goto("/");
  await page.locator("#cash-input").waitFor();
  const today = await page.evaluate(async () => (await (await fetch("/api/cloud-v1/sheets")).json()).todayKl);
  await page.getByRole("button",{name:/添加开销/}).click();
  await page.locator('input[inputmode="decimal"]').nth(2).fill("8.25");
  await page.getByRole("button",{name:"完成此项",exact:true}).click();
  assert.equal(await page.locator(".cost-editor").count(),0);
  assert.equal(await page.locator(".cost-entry-card").count(),1);
  assert.equal(await page.evaluate(async () => (await (await fetch("/api/cloud-v1/sheets")).json()).data),null,"Done collapses a draft; it must not save it");
  await shot("cost-completed-in-draft");
  await page.getByRole("button",{name:/添加开销/}).click();
  await page.locator(".cost-editor select").selectOption("transport");
  await page.locator('input[inputmode="decimal"]').nth(2).fill("12");
  await page.getByRole("button",{name:"完成此项",exact:true}).click();
  assert.equal(await page.locator(".cost-entry-card").count(),2);
  assert.equal(await page.locator(".cost-editor").count(),0);
  await shot("two-compact-costs");
  await page.getByRole("button",{name:/添加开销/}).click();
  await page.locator(".cost-editor select").selectOption("other");
  await page.getByRole("button",{name:"完成此项",exact:true}).click();
  await page.locator("#cost-amount-error-2").waitFor();
  await page.locator('input[inputmode="decimal"]').nth(2).fill("10");
  await page.getByRole("button",{name:"完成此项",exact:true}).click();
  await page.locator("#other-note-error-2").waitFor();
  await shot("done-requires-note");
  await page.locator(".cost-editor .note-input").fill("额外采购");
  await page.getByRole("button",{name:"完成此项",exact:true}).click();
  assert.equal(await page.locator(".cost-editor").count(),0);
  await page.getByRole("button",{name:"前一天",exact:true}).click();
  await page.locator("#cash-input").waitFor();
  await page.getByTitle("日期",{exact:true}).click();
  const pastCalendar=page.getByRole("dialog",{name:"选择日期"});
  const currentDate=await pastCalendar.locator('[aria-current="date"]').getAttribute("aria-label");
  const selectedDate=await pastCalendar.locator('[aria-pressed="true"]').getAttribute("aria-label");
  assert.notEqual(currentDate,selectedDate);
  await shot("today-ring-while-reviewing");
  await page.keyboard.press("Escape");
  await page.getByRole("button",{name:"回到今天",exact:true}).click();
  await page.locator(".date-trigger-label").filter({hasText:today}).waitFor();
  assert.equal(await page.locator(".cost-entry-card").count(),3,"Returning to today must retain its unsaved draft");
  await shot("returned-to-today");
  await page.getByTitle("日期",{exact:true}).click();
  const calendar=page.getByRole("dialog",{name:"选择日期"});
  await calendar.locator('[aria-current="date"]').waitFor();
  await calendar.getByRole("button",{name:"上个月",exact:true}).click();
  await calendar.locator(".calendar-day .calendar-recorded-dot").first().waitFor();
  assert.equal(await calendar.locator(".calendar-day .calendar-recorded-dot").count(),3);
  await shot("recorded-days-calendar");
  await page.keyboard.press("Escape");
  await page.route("**/api/cloud-v1/dashboard*",route=>route.abort());
  await page.getByTitle("日期",{exact:true}).click();
  await page.getByText("暂时无法显示已记录日期",{exact:true}).waitFor();
  await shot("calendar-activity-unavailable");
  await page.keyboard.press("Escape");
  await page.unrouteAll({behavior:"wait"});
  await page.getByRole("button",{name:"前一天",exact:true}).click();
  await page.locator("#cash-input").waitFor();
  await page.setViewportSize({width:320,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  const shortcut=await page.getByRole("button",{name:"回到今天",exact:true}).boundingBox();
  assert(shortcut && shortcut.x>=0 && shortcut.x+shortcut.width<=320);
  await shot("past-date-320");
}
